    @api.model
    def _get_default_type(self):
        task_name = self.name
        task_type = self.env['task.type'].search([('name', 'ilike', f"%{task_name}%")], limit=1)
        return task_type.id if task_type else False

    @api.onchange('level_assurance', 'recorded_amount', 'preliminary_performance_materiality', 'mini_sample_size_2',
                  'mini_sample_size_3', 'mini_sample_size_1')
    def _onchange_sample_size(self):
        for rec in self:
            sample_size_3 = 0
            sample_size_2 = 0
            sample_size_1 = 0
            initial_sample_size = 0
            if rec.preliminary_performance_materiality:
                sample_size_3 = round((rec.recorded_amount * 3) / rec.preliminary_performance_materiality)
                sample_size_2 = round((rec.recorded_amount * 2) / rec.preliminary_performance_materiality)
                sample_size_1 = round((rec.recorded_amount * 1) / rec.preliminary_performance_materiality)
            rec.sample_size_3 = sample_size_3
            rec.final_sample_size_3 = sample_size_3 if sample_size_3 > rec.mini_sample_size_3 else rec.mini_sample_size_3
            rec.sample_size_2 = sample_size_2
            rec.final_sample_size_2 = sample_size_2 if sample_size_2 > rec.mini_sample_size_2 else rec.mini_sample_size_2
            rec.sample_size_1 = sample_size_1
            rec.final_sample_size_1 = sample_size_1 if sample_size_1 > rec.mini_sample_size_1 else rec.mini_sample_size_1
            if rec.level_assurance == '1':
                initial_sample_size = rec.final_sample_size_1
            if rec.level_assurance == '2':
                initial_sample_size = rec.final_sample_size_2
            if rec.level_assurance == '3':
                initial_sample_size = rec.final_sample_size_3
            rec.initial_sample_size = initial_sample_size

    @api.onchange('revised', 'preliminary_materiality_overall',
                  'preliminary_performance_materiality', 'revised_materiality_overall',
                  'revised_performance_materiality')
    def _onchange_materiality(self):
        """Onchange Materiality"""
        for rec in self:
            final_materiality_overall = rec.preliminary_materiality_overall
            final_performance_materiality = rec.preliminary_performance_materiality
            if rec.revised == 'yes':
                final_materiality_overall = rec.revised_materiality_overall if rec.revised_materiality_overall != 0 else rec.preliminary_materiality_overall
                final_performance_materiality = rec.revised_performance_materiality if rec.revised_performance_materiality != 0 else rec.preliminary_performance_materiality
            rec.final_materiality_overall = final_materiality_overall
            rec.final_performance_materiality = final_performance_materiality

    @api.onchange('hr_team_id')
    def _onchange_team_id(self):
        """Onchange Team"""
        for rec in self:
            user = []
            user_reviewer_2 = []
            user_approver = []
            users = []
            if rec.hr_team_id:
                users = rec.hr_team_id.employee_ids.mapped('user_id')
                user = [
                    employee.user_id.id
                    for employee in rec.hr_team_id.employee_ids
                    if any(role.type == 'Reviewer_1' for role in employee.role_ids)
                ]
                user_reviewer_2 = [
                    employee.user_id.id
                    for employee in rec.hr_team_id.employee_ids
                    if
                    any(role.type == 'Reviewer_2' for role in employee.role_ids)
                ]
                user_approver = [
                    employee.user_id.id
                    for employee in rec.hr_team_id.employee_ids
                    if
                    any(role.type == 'Approver' for role in employee.role_ids)
                ]
            rec.user_reviewer_1_ids = user
            rec.user_reviewer_2_ids = user_reviewer_2
            rec.user_approver = user_approver
            rec.user_ids = users

    @api.model_create_multi
    def create(self, vals_list):
        """Support multi-create and single-create paths safely (used during XML data load)."""
        # Accept both dict and list-of-dicts (some code might call with dict unexpectedly)
        if isinstance(vals_list, dict):
            vals_list = [vals_list]

        prepared = []
        for vals in vals_list:
            v = dict(vals or {})

            # parent-based defaults
            if v.get('parent_id'):
                parent_id = self.env['project.task'].browse(int(v.get('parent_id')))
                v['stage_id'] = parent_id.stage_id.id or False
                v['type'] = parent_id.type.id if parent_id.type else False
                prefix = parent_id.stage_id.prefix if parent_id.stage_id and parent_id.stage_id.prefix else ""
                reference_number = prefix + ': ' + str(
                    parent_id.sub_task_count + 1) if prefix or parent_id.sub_task_count is not None else False
                v['reference_number'] = reference_number

            # project-based defaults
            if v.get('project_id'):
                project_id = self.env['project.project'].browse(int(v.get('project_id')))
                if project_id and project_id.department_id:
                    v['hr_team_id'] = project_id.department_id.id
                    v['user_ids'] = project_id.team_member_ids.mapped('user_id').ids
                    # keep the rest as before (commented-out defaults left out to avoid unexpected writes)

            prepared.append(v)

        # Try bulk create (preferred). If parent/other modules are not multi-create aware, fall back to per-record create.
        try:
            records = super(ProjectTask, self).create(prepared)
        except Exception:
            records = self.browse()
            for v in prepared:
                try:
                    rec = super(ProjectTask, self).create(v)
                except TypeError:
                    # some parent implementations expect a list; try with single-item list
                    rec = super(ProjectTask, self).create([v])
                records |= rec
        return records

    @api.onchange('child_ids')
    def _compute_sub_task_count(self):
        """Calculate the sub-tasks"""
        for rec in self:
            rec.sub_task_count = len(rec.child_ids)

