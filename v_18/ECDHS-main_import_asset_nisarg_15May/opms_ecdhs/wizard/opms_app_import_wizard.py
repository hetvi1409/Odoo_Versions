    def _value_to_text(self, value):
        if value is None:
            return ""
        if hasattr(value, "strftime"):
            return value.strftime("%d/%m/%Y")
        return str(value).strip()

    def _load_rows(self):
        if not self.file_data:
            raise UserError(_("Please upload an Excel file."))

        workbook = openpyxl.load_workbook(io.BytesIO(base64.b64decode(self.file_data)), data_only=True)
        sheet = workbook[workbook.sheetnames[0]]

        header_row = [self._value_to_text(sheet.cell(row=1, column=col).value) for col in range(1, sheet.max_column + 1)]
        headers = [value for value in header_row if value]

        missing = []
        for column in REQUIRED_COLUMNS:
            aliases = REQUIRED_COLUMN_ALIASES.get(column, [column])
            if not any(alias in headers for alias in aliases):
                missing.append(column)
        if missing:
            raise UserError(_("Missing required columns: %s") % ", ".join(missing))

        index_by_header = {header: i for i, header in enumerate(header_row)}

        data_rows = []
        for row_num in range(2, sheet.max_row + 1):
            row_values = [sheet.cell(row=row_num, column=col).value for col in range(1, sheet.max_column + 1)]
            if not any(value is not None and str(value).strip() for value in row_values):
                continue

            item = {}
            for column in header_row:
                if not column:
                    continue
                item[column] = row_values[index_by_header[column]]
            item["_row_number"] = row_num
            data_rows.append(item)

        if not data_rows:
            raise UserError(_("No importable rows were found in the spreadsheet."))

        return data_rows

