    # ── Feature 1 – Auto-import the bundled Excel file ──────────────────────

    def action_auto_import_from_excel(self):
        """Cleanse the bundled KPI Excel (or a selected versioned copy), save a
        corrected versioned copy, then run the standard import from it."""
        self.ensure_one()
        self._ensure_operation_mode("auto_import")
        if not self.financial_year:
            raise UserError(_("Please select a Financial Year before running the auto-import."))

        data_dir = self._module_data_path()

        # ── Determine source file ─────────────────────────────────────────────
        if self.versioned_excel_file:
            # User wants to re-use a previously corrected version as-is
            source_path = os.path.join(data_dir, self.versioned_excel_file)
            if not os.path.exists(source_path):
                raise UserError(
                    _("Selected corrected file not found: %s") % source_path
                )
            with open(source_path, "rb") as fh:
                encoded = base64.b64encode(fh.read())
            self.write({"file_data": encoded, "file_name": self.versioned_excel_file})
            return self.action_import_app()

        # ── Load original bundled file ────────────────────────────────────────
        original_name = "KPI 2025-26_Remapped-UPDATED.xlsx"
        original_path = os.path.join(data_dir, original_name)
        if not os.path.exists(original_path):
            raise UserError(
                _(
                    "Bundled Excel file not found.\n"
                    "Expected location: %s\n\n"
                    "Ensure the file exists in the module's /data/ directory."
                )
                % original_path
            )

        with open(original_path, "rb") as fh:
            source_bytes = fh.read()

        # ── Cleanse & correct ─────────────────────────────────────────────────
        corrected_bytes, corrections_log = self._cleanse_excel_workbook(source_bytes)

        # ── Determine versioned filename ──────────────────────────────────────
        versioned_name = self._next_versioned_filename(data_dir, original_name)
        versioned_path = os.path.join(data_dir, versioned_name)

        try:
            os.makedirs(data_dir, exist_ok=True)
            with open(versioned_path, "wb") as fh:
                fh.write(corrected_bytes)
        except OSError as exc:
            _logger.warning(
                "opms_app_import_wizard: could not save versioned Excel to %s: %s",
                versioned_path,
                exc,
            )
            versioned_name = original_name  # fall back to original name for audit trail

        # ── Import from the corrected copy ────────────────────────────────────
        encoded = base64.b64encode(corrected_bytes)
        self.write({"file_data": encoded, "file_name": versioned_name})
        result = self.action_import_app()

        # Record the versioned filename in the most recent import history
        # This enables cascade cleanup when the APP Plan is deleted
        latest_history = self.env["opms.import.history"].search(
            [("financial_year", "=", self.financial_year.id)],
            order="id desc",
            limit=1,
        )
        if latest_history:
            # Find the APP Plan created/updated in this import
            app_plan = self.env["opms.app.plan"].search(
                [
                    ("name", "like", "ANNUAL PERFORMANCE"),
                    ("financial_year", "=", self.financial_year.id),
                ],
                order="id desc",
                limit=1,
            )
            latest_history.write({
                "versioned_excel_filename": versioned_name,
                "app_plan_id": app_plan.id if app_plan else False,
            })

        # Amend the notification to mention the saved path and corrections
        if result.get("type") == "ir.actions.client" and result.get("tag") == "display_notification":
            orig_msg = result["params"]["message"]
            result["params"]["message"] = (
                f"{orig_msg}\n\n"
                f"Corrected file saved as: {versioned_name}\n"
                f"Corrections applied: {corrections_log}"
            )
            result["params"]["sticky"] = True

        return result

    # ── Excel cleansing helpers ──────────────────────────────────────────────

    def _cleanse_excel_workbook(self, source_bytes):
        """Load *source_bytes*, apply all corrections, return (corrected_bytes, summary_str).

        Corrections applied:
        * All text cells: strip leading/trailing whitespace and embedded newlines
        * Numeric int/float cells in target columns: converted to str (e.g. 6 → "6")
        * datetime cells in target columns: converted to "DD/MM/YYYY" string
        * Dash-variant cells (" - \\n\\n", "  -  " etc.): normalised to "-"
        * Annual_Target / Q*_Planned: parenthetical notes stripped
          e.g. "4 (Events, ...)" → "4"
        * Adds a ``Measurement_Type`` column with correctly inferred type per row
        * Adds a ``Measurement_Unit`` column with an inferred unit per row
        """
        wb_src = openpyxl.load_workbook(io.BytesIO(source_bytes), data_only=True)
        ws_src = wb_src[wb_src.sheetnames[0]]

        wb_dst = openpyxl.Workbook()
        ws_dst = wb_dst.active
        ws_dst.title = ws_src.title

        # ── Copy & normalise header row ───────────────────────────────────────
        headers = []
        for col_idx in range(1, ws_src.max_column + 1):
            raw = ws_src.cell(row=1, column=col_idx).value
            header_text = self._vt_strip(raw)
            headers.append(header_text)
            ws_dst.cell(row=1, column=col_idx, value=header_text)

        # Append extra columns if not already present
        mtype_col = self._ensure_column(headers, ws_dst, "Measurement_Type")
        munit_col = self._ensure_column(headers, ws_dst, "Measurement_Unit")

        target_cols = {"Annual_Target", "Q1_Planned", "Q2_Planned", "Q3_Planned", "Q4_Planned"}

        counts = {"stripped": 0, "date_converted": 0, "num_converted": 0, "dash_normalised": 0, "paren_stripped": 0}

        # ── Process data rows ─────────────────────────────────────────────────
        for row_num in range(2, ws_src.max_row + 1):
            row_values = [ws_src.cell(row=row_num, column=c).value for c in range(1, ws_src.max_column + 1)]

            if not any(v is not None and str(v).strip() for v in row_values):
                continue  # skip entirely blank rows

            cleaned_row = {}

            for col_idx, header in enumerate(headers):
                if not header:
                    continue
                raw = row_values[col_idx] if col_idx < len(row_values) else None
                cleaned = self._clean_cell_value(
                    raw,
                    header,
                    is_target_col=(header in target_cols),
                    counts=counts,
                )
                cleaned_row[header] = cleaned
                ws_dst.cell(row=row_num, column=col_idx + 1, value=cleaned)

            # ── Infer measurement type & unit ─────────────────────────────────
            ind_name = cleaned_row.get("Output_ Indicator") or ""
            ann_target = cleaned_row.get("Annual_Target") or ""
            q_values = {
                "q1": cleaned_row.get("Q1_Planned") or "",
                "q2": cleaned_row.get("Q2_Planned") or "",
                "q3": cleaned_row.get("Q3_Planned") or "",
                "q4": cleaned_row.get("Q4_Planned") or "",
            }

            existing_mtype = (
                cleaned_row.get("Measurement_Type")
                or cleaned_row.get("Measurement Type")
                or ""
            )
            mtype = self._cleanse_infer_mtype(ind_name, ann_target, q_values, existing_mtype)
            munit = self._cleanse_infer_munit(ind_name, ann_target, q_values, mtype)

            ws_dst.cell(row=row_num, column=mtype_col, value=mtype)
            ws_dst.cell(row=row_num, column=munit_col, value=munit)

        buf = io.BytesIO()
        wb_dst.save(buf)
        corrected_bytes = buf.getvalue()

        summary = (
            f"stripped_whitespace={counts['stripped']}, "
            f"dates_converted={counts['date_converted']}, "
            f"numbers_converted={counts['num_converted']}, "
            f"dashes_normalised={counts['dash_normalised']}, "
            f"parentheticals_stripped={counts['paren_stripped']}"
        )
        return corrected_bytes, summary

    def _vt_strip(self, value):
        """Convert any cell value to a clean string (strip newlines/whitespace)."""
        if value is None:
            return ""
        if isinstance(value, (datetime, date)):
            return value.strftime("%d/%m/%Y")
        return re.sub(r"[\r\n]+", " ", str(value)).strip()

    def _ensure_column(self, headers, ws_dst, column_name):
        """Return the 1-based column index for *column_name*, adding it if absent."""
        for i, h in enumerate(headers):
            if h == column_name:
                return i + 1
        # Add at end
        new_col = len(headers) + 1
        headers.append(column_name)
        ws_dst.cell(row=1, column=new_col, value=column_name)
        return new_col

    def _clean_cell_value(self, raw, header, is_target_col, counts):
        """Return the cleaned value for a single cell."""
        if raw is None:
            return None

        # datetime / date objects → formatted string
        if isinstance(raw, (datetime, date)):
            cleaned = raw.strftime("%d/%m/%Y")
            counts["date_converted"] += 1
            return cleaned

        # numeric int / float → string
        if isinstance(raw, (int, float)) and is_target_col:
            cleaned = str(int(raw)) if float(raw).is_integer() else str(raw)
            counts["num_converted"] += 1
            return cleaned

        if not isinstance(raw, str):
            return raw

        # Strip embedded newlines and leading/trailing whitespace
        cleaned = re.sub(r"[\r\n]+", " ", raw).strip()
        if cleaned != raw:
            counts["stripped"] += 1

        # Normalise dash variants (e.g. " - ", "  -  ", "-  ")
        if is_target_col and re.fullmatch(r"[\s\-–—]+", cleaned):
            counts["dash_normalised"] += 1
            return "-"

        # Strip trailing parenthetical notes from target columns that start with a number
        # e.g. "4 (Events, Internal Communication ...)" → "4"
        if is_target_col:
            paren_stripped = re.sub(r"\s*\(.*\)\s*$", "", cleaned).strip()
            if paren_stripped != cleaned and re.match(r"^[-+]?\d+(?:[.,]\d+)?", paren_stripped):
                counts["paren_stripped"] += 1
                return paren_stripped

        return cleaned

    def _cleanse_infer_mtype(self, indicator_name, annual_target, q_values, existing_mtype):
        """Improved measurement-type inference used during cleansing.

        Unlike the wizard's _infer_measurement_type, this uses word-boundary checks
        so that 'updates' does not incorrectly trigger the 'date' branch, and
        'percentage' / 'percent' take priority over 'date' keywords.
        """
        if existing_mtype and existing_mtype.lower() in MEASUREMENT_TYPE_ALIASES:
            return MEASUREMENT_TYPE_ALIASES[existing_mtype.lower()]

        text = (str(indicator_name or "")).lower().strip()
        cands = [annual_target] + list(q_values.values())

        # 1. Percentage takes highest priority (avoids "30 days from date of …")
        if re.search(r"\bpercentage\b|\bpercent\b", text):
            return "percentage"
        if any("%" in str(v or "") for v in cands):
            return "percentage"

        # 2. Date — use word boundary so "updates" ≠ "date"
        if any(isinstance(v, (date, datetime)) for v in cands):
            return "date"
        # Check string values that look like dates
        for v in cands:
            t = str(v or "").strip()
            if t and t.lower() not in ("-", "n/a", "na") and re.search(
                r"\b\d{1,2}[/\-]\d{1,2}[/\-]\d{2,4}\b|\b\d{4}-\d{2}-\d{2}\b"
                r"|\b\d{1,2}\s+(?:January|February|March|April|May|June|July"
                r"|August|September|October|November|December)\s+\d{4}\b",
                t,
                re.IGNORECASE,
            ):
                return "date"
        if re.search(r"\bdate\b|\bdeadline\b|\btimeline\b", text) or "within the prescribed timelines" in text:
            return "date"

        # 3. Boolean
        if (
            re.search(r"\bachieved\b|\bcompliant\b|\bapproved\b|\bcompleted\b|\bimplemented\b", text)
            and "number of" not in text
        ):
            return "boolean"

        # 4. Milestone
        if (
            re.search(r"\bmilestone\b|\bsubmission of\b|\btabling of\b", text)
            and "number of" not in text
        ):
            return "milestone"

        return "number"

    def _cleanse_infer_munit(self, indicator_name, annual_target, q_values, mtype):
        """Infer a measurement unit string for the cleansed Excel Measurement_Unit column."""
        if mtype != "number":
            return ""

        # Try extracting a unit from target values (e.g. "30 days" → "days")
        cands = [annual_target] + list(q_values.values())
        for v in cands:
            t = str(v or "").strip()
            if not t or t == "-":
                continue
            m = re.match(r"^\s*[-+]?\d+(?:[.,]\d+)?\s+([a-zA-Z][a-zA-Z0-9 _/%-]*)\s*$", t)
            if m:
                return m.group(1).strip()

        # Extract noun phrase from "Number of <noun>" indicators
        text = str(indicator_name or "").strip()
        m = re.match(r"^[Nn]umber\s+of\s+(.+)", text)
        if m:
            noun = m.group(1).strip()
            # Drop trailing past-tense verbs that are not the core unit
            noun = re.sub(
                r"\s+(conducted|submitted|coordinated|performed|implemented|approved"
                r"|developed|prepared|tabled|supported|completed|achieved|installed"
                r"|delivered|reviewed|allocated|finalized|updated|verified|produced"
                r"|compiled|processed|generated|issued|presented|recruited|trained"
                r"|identified|engaged|registered|administered|established|monitored"
                r"|assessed|facilitated|provided|resolved|rectified|attended"
                r"|supported|undertaken|inspected)\s*$",
                "",
                noun,
                flags=re.IGNORECASE,
            ).strip()
            words = noun.split()
            unit = " ".join(words[:3]) if len(words) > 3 else noun
            return unit if unit else "count"

        return "count"

    @staticmethod
    def _next_versioned_filename(data_dir, original_name):
        """Return the next versioned filename, e.g. 'KPI 2025-26_Remapped-UPDATED-v3-07-05-2026.xlsx'."""
        base = os.path.splitext(original_name)[0]  # strip .xlsx
        today_str = date.today().strftime("%d-%m-%Y")
        # Accept both historical '-3-' and required '-v3-' formats when computing next version.
        pattern = re.compile(re.escape(base) + r"-(?:v)?(\d+)-\d{2}-\d{2}-\d{4}\.xlsx$", re.IGNORECASE)

        max_version = 0
        try:
            existing_files = os.listdir(data_dir)
        except OSError:
            existing_files = []
        for fname in existing_files:
            m = pattern.match(fname)
            if m:
                max_version = max(max_version, int(m.group(1)))

        new_version = max_version + 1
        return f"{base}-v{new_version}-{today_str}.xlsx"

    # ── Feature 2 – Copy hierarchy from a previous period ───────────────────

    def action_copy_from_previous_period(self):
        """Copy the full APP hierarchy (APP Plan → Annual Targets → Quarters →
        Quarterly Targets) from a source financial year into the selected
        target financial year.  Dates are shifted by the FY offset where
        possible."""
        self.ensure_one()
        self = self.with_context(
            opms_skip_live_sync_refresh=True,
            opms_import_app_matrix=True,
        )
        self._ensure_operation_mode("copy_previous")
        if not self.financial_year:
            raise UserError(_("Please select a target Financial Year."))
        if not self.source_financial_year:
            raise UserError(_("Please select a source Financial Year to copy data from."))
        if self.source_financial_year == self.financial_year:
            raise UserError(_("Source and target Financial Years must be different."))

        target_fy = self.financial_year
        source_fy = self.source_financial_year

        date_delta = None
        if source_fy.date_from and target_fy.date_from:
            date_delta = target_fy.date_from - source_fy.date_from

        source_plans = self.env["opms.app.plan"].search([("financial_year", "=", source_fy.id)])
        if not source_plans:
            raise UserError(
                _("No APP Plans found for '%s'. Nothing to copy.") % source_fy.display_name
            )

        tune = self._get_import_progress_tuning()
        created_plans = created_annual = created_quarterly = 0
        target_plans_by_name = {
            rec.name: rec
            for rec in self.env["opms.app.plan"].search([("financial_year", "=", target_fy.id)])
        }

        self._notify_progress(
            _("Copy Previous Progress"),
            _("Starting copy from %s to %s for %s APP Plan(s).")
            % (source_fy.display_name, target_fy.display_name, len(source_plans)),
        )

        for plan_index, source_plan in enumerate(source_plans, start=1):
            plan_name = source_plan.name
            if source_fy.name and target_fy.name and source_fy.name in plan_name:
                plan_name = plan_name.replace(source_fy.name, target_fy.name)

            target_plan = target_plans_by_name.get(plan_name)
            if not target_plan:
                target_plan = self.env["opms.app.plan"].create({
                    "name": plan_name,
                    "financial_year": target_fy.id,
                    "code": target_fy.name,
                })
                target_plans_by_name[plan_name] = target_plan
                created_plans += 1

            # Build source-quarter → target-quarter mapping
            quarter_map = {}
            source_quarters = self.env["opms.quarter"].search([
                ("app_plan_id", "=", source_plan.id),
                ("financial_year", "=", source_fy.id),
            ])
            target_quarters_by_code = {
                rec.code: rec
                for rec in self.env["opms.quarter"].search([
                    ("app_plan_id", "=", target_plan.id),
                    ("financial_year", "=", target_fy.id),
                ])
            }
            for sq in source_quarters:
                tq = target_quarters_by_code.get(sq.code)
                if not tq:
                    q_vals = {
                        "name": sq.name,
                        "code": sq.code,
                        "financial_year": target_fy.id,
                        "app_plan_id": target_plan.id,
                    }
                    if date_delta:
                        for date_fld in (
                            "start_date", "end_date",
                            "submission_open_date", "submission_close_date",
                        ):
                            src_date = getattr(sq, date_fld)
                            if src_date:
                                q_vals[date_fld] = src_date + date_delta
                    tq = self.env["opms.quarter"].create(q_vals)
                    target_quarters_by_code[sq.code] = tq
                quarter_map[sq.id] = tq

            # Copy annual targets (Programmes / Directorates / Indicators reused as-is)
            source_annual_targets = self.env["opms.annual.target"].search([
                ("app_plan_id", "=", source_plan.id),
                ("financial_year", "=", source_fy.id),
            ])
            target_annual_targets_by_indicator = {
                rec.output_indicator_id.id: rec
                for rec in self.env["opms.annual.target"].search([
                    ("app_plan_id", "=", target_plan.id),
                    ("financial_year", "=", target_fy.id),
                ])
            }
            source_quarterly_by_annual = {}
            source_quarterly_targets = self.env["opms.quarterly.target"].search([
                ("annual_target_id", "in", source_annual_targets.ids),
            ])
            for sqt in source_quarterly_targets:
                source_quarterly_by_annual.setdefault(sqt.annual_target_id.id, []).append(sqt)

            target_quarterly_pairs = set()
            if target_annual_targets_by_indicator:
                existing_target_quarterlies = self.env["opms.quarterly.target"].search([
                    ("annual_target_id", "in", list(rec.id for rec in target_annual_targets_by_indicator.values())),
                ])
                target_quarterly_pairs = {
                    (rec.annual_target_id.id, rec.quarter_id.id) for rec in existing_target_quarterlies
                }

            for sat in source_annual_targets:
                tat = target_annual_targets_by_indicator.get(sat.output_indicator_id.id)
                if not tat:
                    tv = sat.target_value
                    if sat.output_indicator_id.measurement_type == "date" and date_delta:
                        tv = self._shift_date_string(tv, date_delta)
                    tv = self._normalize_value_for_indicator(sat.output_indicator_id, tv)
                    tat = self.env["opms.annual.target"].with_context(import_file=True).create({
                        "output_indicator_id": sat.output_indicator_id.id,
                        "app_plan_id": target_plan.id,
                        "financial_year": target_fy.id,
                        "target_value": tv,
                    })
                    target_annual_targets_by_indicator[sat.output_indicator_id.id] = tat
                    created_annual += 1

                # Copy quarterly targets
                for sqt in source_quarterly_by_annual.get(sat.id, []):
                    tq = quarter_map.get(sqt.quarter_id.id)
                    if not tq:
                        continue
                    quarterly_key = (tat.id, tq.id)
                    if quarterly_key not in target_quarterly_pairs:
                        pt = sqt.planned_target
                        if sat.output_indicator_id.measurement_type == "date" and date_delta:
                            pt = self._shift_date_string(pt, date_delta)
                        pt = self._normalize_value_for_indicator(sat.output_indicator_id, pt)
                        self.env["opms.quarterly.target"].create({
                            "annual_target_id": tat.id,
                            "quarter_id": tq.id,
                            "planned_target": pt,
                        })
                        target_quarterly_pairs.add(quarterly_key)
                        created_quarterly += 1

            if plan_index % tune["copy_plan_notify_step"] == 0:
                self._notify_progress(
                    _("Copy Previous Progress"),
                    _("Processed %s/%s APP Plan(s). Created: %s plans, %s annual targets, %s quarterly targets.")
                    % (plan_index, len(source_plans), created_plans, created_annual, created_quarterly),
                )

        self._notify_progress(
            _("Copy Previous Progress"),
            _("Copy completed from %s to %s. Created: %s plans, %s annual targets, %s quarterly targets.")
            % (source_fy.display_name, target_fy.display_name, created_plans, created_annual, created_quarterly),
        )

        return {
            "type": "ir.actions.client",
            "tag": "display_notification",
            "params": {
                "title": _("Copy Complete"),
                "message": _(
                    "Copied from %s → %s:\n"
                    "%s APP Plan(s), %s Annual Targets, %s Quarterly Targets created."
                ) % (
                    source_fy.display_name, target_fy.display_name,
                    created_plans, created_annual, created_quarterly,
                ),
                "type": "success",
                "sticky": True,
            },
        }

    def _shift_date_string(self, value, delta):
        """Attempt to shift a date string by *delta* (timedelta).
        Returns the original string unchanged if it cannot be parsed."""
        text = (self._value_to_text(value) or "").strip()
        if not text:
            return value
        for fmt in ("%Y-%m-%d", "%d/%m/%Y", "%d-%m-%Y", "%m/%d/%Y", "%d %B %Y", "%d %b %Y"):
            try:
                shifted = datetime.strptime(text, fmt).date() + delta
                return shifted.strftime(fmt)
            except ValueError:
                continue
        return value

