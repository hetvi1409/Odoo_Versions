    @staticmethod
    def _module_data_path():
        import odoo.modules as _odoo_modules
        module_path = _odoo_modules.get_module_path("opms_ecdhs")
        return os.path.join(module_path, "data")

    def _get_versioned_file_selection(self):
        try:
            data_dir = self._module_data_path()
            pattern = re.compile(r"KPI.*-(?:v)?\d{1,4}-\d{2}-\d{2}-\d{4}\.xlsx$", re.IGNORECASE)
            files = sorted(
                f for f in os.listdir(data_dir)
                if pattern.match(f) and os.path.isfile(os.path.join(data_dir, f))
            )
            return [(f, f) for f in files]
        except Exception:
            return []

    def _default_financial_year(self):
        self.env["opms.app.plan"]._ensure_opms_fiscal_years()
        today = fields.Date.context_today(self)
        return self.env["account.fiscal.year"].search(
            [("date_from", "<=", today), ("date_to", ">=", today)],
            order="date_from desc",
            limit=1,
        )

