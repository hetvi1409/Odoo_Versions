    def _parse_directorate(self, directorate_name):
        value = (directorate_name or "").strip()
        match = re.match(r"^(\d+)(?:\.(\d+))?(?:\.(\d+))?\s*(.*)$", value)
        if not match:
            return {
                "programme_code": "",
                "sub_programme_code": "",
                "directorate_code": "",
                "directorate_label": value,
            }

        p1, p2, p3, label = match.groups()
        programme_code = p1
        sub_programme_code = f"{p1}.{p2}" if p2 else p1
        directorate_code = ".".join([part for part in [p1, p2, p3] if part])
        directorate_label = f"{directorate_code} {label.strip()}".strip()

        return {
            "programme_code": programme_code,
            "sub_programme_code": sub_programme_code,
            "directorate_code": directorate_code,
            "directorate_label": directorate_label,
        }

