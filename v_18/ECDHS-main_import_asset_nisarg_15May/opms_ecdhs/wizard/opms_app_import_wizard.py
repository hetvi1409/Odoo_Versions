    def _collect_demo_plan_indicators(self):
        """Collect indicator definitions from the best available source.

        Source priority:
        1. ``demo_source_url`` starting with http/https (download PDF, extract text).
        2. ``demo_source_url`` as a local path (relative to /data/ or absolute).
        3. Uploaded ``file_data`` when ``file_name`` ends with ``.pdf``.
        4. Bundled KPI Excel file in /data/.
        5. Built-in fallback indicator set.
        """
        url = (self.demo_source_url or "").strip()

        # 1. Remote URL
        if url.lower().startswith(("http://", "https://")):
            try:
                content = self._fetch_url_bytes(url)
                parsed = self._parse_indicators_from_text(self._extract_text_from_pdf_bytes(content))
                if parsed:
                    _logger.info("opms demo_app_plans: %d indicator(s) from URL %s", len(parsed), url)
                    return parsed
                _logger.warning("opms demo_app_plans: no indicators extracted from URL %s, falling back", url)
            except Exception as exc:
                _logger.warning("opms demo_app_plans: URL extraction failed (%s), falling back", exc)

        # 2. Local file path
        elif url:
            local_path = url if os.path.isabs(url) else os.path.join(self._module_data_path(), url)
            try:
                with open(local_path, "rb") as fh:
                    content = fh.read()
                if local_path.lower().endswith(".pdf"):
                    parsed = self._parse_indicators_from_text(self._extract_text_from_pdf_bytes(content))
                else:
                    parsed = self._extract_indicators_from_excel(content)
                if parsed:
                    return parsed
            except Exception as exc:
                _logger.warning("opms demo_app_plans: local path extraction failed (%s), falling back", exc)

        # 3. Uploaded PDF
        if self.file_data and (self.file_name or "").lower().endswith(".pdf"):
            try:
                parsed = self._parse_indicators_from_text(
                    self._extract_text_from_pdf_bytes(base64.b64decode(self.file_data))
                )
                if parsed:
                    return parsed
            except Exception as exc:
                _logger.warning("opms demo_app_plans: uploaded PDF extraction failed (%s), falling back", exc)

        # 4. Bundled Excel
        try:
            excel_path = os.path.join(self._module_data_path(), "KPI 2025-26_Remapped-UPDATED.xlsx")
            if os.path.exists(excel_path):
                with open(excel_path, "rb") as fh:
                    parsed = self._extract_indicators_from_excel(fh.read())
                if parsed:
                    _logger.info("opms demo_app_plans: %d indicator(s) from bundled Excel", len(parsed))
                    return parsed
        except Exception as exc:
            _logger.warning("opms demo_app_plans: bundled Excel extraction failed (%s), falling back", exc)

        # 5. Built-in fallback
        return self._DEMO_INDICATOR_FALLBACK[:]

    def _extract_indicators_from_excel(self, excel_bytes):
        """Extract unique indicator names from an Excel workbook and infer properties."""
        try:
            wb = openpyxl.load_workbook(io.BytesIO(excel_bytes), data_only=True, read_only=True)
            ws = wb[wb.sheetnames[0]]
            headers = [self._value_to_text(ws.cell(1, c).value) for c in range(1, ws.max_column + 1)]
            ind_col = next(
                (i + 1 for i, h in enumerate(headers)
                 if h in ("Output_ Indicator", "Output Indicator", "Indicator")),
                None,
            )
            if not ind_col:
                return []
            seen = set()
            result = []
            for row_num in range(2, ws.max_row + 1):
                name = self._value_to_text(ws.cell(row_num, ind_col).value).strip()
                if name and name not in seen and len(name) >= 10:
                    seen.add(name)
                    mtype = self._infer_measurement_type(name, None, {})
                    result.append({
                        "name": name,
                        "measurement_type": mtype,
                        "aggregation_rule": self._infer_aggregation_rule(mtype, name),
                        "comparison_direction": self._infer_comparison_direction(mtype, name),
                    })
            return result
        except Exception:
            return []

    def _extract_text_from_pdf_bytes(self, pdf_bytes):
        """Extract plain text from PDF bytes using the best available library.

        Attempts: pypdf → PyPDF2 → pdfminer.six → raw byte scan.
        """
        for mod_name in ("pypdf", "PyPDF2"):
            try:
                mod = __import__(mod_name)
                reader_cls = getattr(mod, "PdfReader", None) or getattr(mod, "PdfFileReader", None)
                if reader_cls:
                    reader = reader_cls(io.BytesIO(pdf_bytes))
                    pages = getattr(reader, "pages", None)
                    if pages is None:
                        pages = [reader.getPage(i) for i in range(reader.numPages)]
                    texts = []
                    for page in pages:
                        fn = getattr(page, "extract_text", None) or getattr(page, "extractText", None)
                        texts.append(fn() or "" if fn else "")
                    return "\n".join(texts)
            except ImportError:
                continue
            except Exception:
                continue

        # Try pdfminer.six
        try:
            from pdfminer.high_level import extract_text as _pdfminer_extract  # noqa: PLC0415
            return _pdfminer_extract(io.BytesIO(pdf_bytes))
        except ImportError:
            pass
        except Exception:
            pass

        # Last resort: scan raw PDF bytes for readable string literals
        try:
            text = pdf_bytes.decode("latin-1", errors="replace")
            parts = re.findall(r"\(([^()]{10,250})\)", text)
            return "\n".join(parts)
        except Exception:
            return ""

    def _fetch_url_bytes(self, url):
        """Download *url* and return the raw response bytes."""
        import urllib.request  # noqa: PLC0415
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 (OPMS/1.0)"})
            with urllib.request.urlopen(req, timeout=30) as response:
                return response.read()
        except Exception as exc:
            raise UserError(_("Could not download from URL: %s\n\nError: %s") % (url, exc))

    def _parse_indicators_from_text(self, text):
        """Extract performance-indicator-like lines from plain text (e.g. PDF extract)."""
        if not text:
            return []
        result = []
        seen = set()
        for line in text.splitlines():
            line = re.sub(r"\s+", " ", line).strip()
            if not line or len(line) < 15 or len(line) > 350:
                continue
            # Skip lines that are clearly not indicator sentences
            if re.fullmatch(r"[\d\s.,:;/\\()\-]+", line):
                continue
            if re.match(r"^\s*(?:page|table|figure|section|chapter|appendix)\s*\d*\s*$", line, re.IGNORECASE):
                continue
            # Accept lines that contain indicator-pattern keywords
            if re.search(
                r"\b(number of|percentage|rate of|proportion|level of|degree of|extent to|"
                r"average number|achieved|implemented|submitted|approved|completed|conducted|"
                r"developed|established|maintained|reviewed|finalised|finalized|tabled|"
                r"published|issued|registered|verified|inspected|assessed|audited)\b",
                line, re.IGNORECASE,
            ):
                if line not in seen:
                    seen.add(line)
                    mtype = self._infer_measurement_type(line, None, {})
                    result.append({
                        "name": line,
                        "measurement_type": mtype,
                        "aggregation_rule": self._infer_aggregation_rule(mtype, line),
                        "comparison_direction": self._infer_comparison_direction(mtype, line),
                    })
                    if len(result) >= 300:
                        break
        return result

    def _demo_random_planned_value(self, rng, measurement_type, quarter_code=None, fy=None, is_annual=False):
        """Return a plausible randomised planned target value for demo plan generation."""
        if measurement_type == "number":
            base = rng.randint(3, 24)
            return str(base * 4 if is_annual else base)

        if measurement_type == "percentage":
            return str(rng.randint(70, 95))

        if measurement_type == "date":
            fy_end = (fy.date_to if fy and fy.date_to else date.today())
            fy_start = (fy.date_from if fy and fy.date_from else fy_end.replace(month=4, day=1))
            span = max(1, (fy_end - fy_start).days)
            if is_annual:
                return fy_end.strftime("%Y-%m-%d")
            q_num = {"q1": 1, "q2": 2, "q3": 3, "q4": 4}.get(quarter_code or "q4", 4)
            q_end = fy_start + timedelta(days=span * q_num // 4)
            return q_end.strftime("%Y-%m-%d")

        if measurement_type == "boolean":
            return "Yes"

        if measurement_type == "milestone":
            return rng.choice([
                "Annual report tabled in Parliament by the stipulated deadline",
                "Strategy document submitted and approved by the Executive Authority",
                "Implementation plan developed and approved by the Accounting Officer",
                "Review report finalized and submitted to the relevant committee",
                "Service delivery improvement plan published on the departmental website",
            ])

        # text / default
        return "Activity fully completed as per the approved operational plan"

    # ── Feature 4 – Load demo seed submissions ──────────────────────────────
    # Visible to Settings / Administrator group only (enforced in the view).

    def action_load_demo_submissions(self):
        """Generate scrambled demo submissions for every quarterly target in the
        selected financial year.  A dummy evidence file is attached to every
        non-draft submission so the portal workflow operates correctly."""
        self.ensure_one()
        self._ensure_operation_mode("demo_submissions", admin_required=True)
        if not self.financial_year:
            raise UserError(_("Please select a Financial Year to load demo submissions for."))

        fy = self.financial_year
        rng = random.Random()  # non-deterministic — each run produces a different scramble

        quarterly_targets = self.env["opms.quarterly.target"].search(
            [("financial_year", "=", fy.id)]
        )
        if not quarterly_targets:
            raise UserError(
                _(
                    "No quarterly targets found for '%s'.\n"
                    "Please import the APP Matrix first before loading demo submissions."
                )
                % fy.display_name
            )

        # Delete all existing demo submissions for this FY so the run is fully fresh
        existing_demos = self.env["opms.reporting.submission"].search(
            [("name", "like", "[DEMO]"), ("financial_year", "=", fy.id)]
        )
        if existing_demos:
            existing_demos.sudo().unlink()

        tune = self._get_demo_seed_tuning()
        dummy_evidence = base64.b64encode(_DUMMY_EVIDENCE_BYTES)
        created = skipped = 0
        prepared_rows = []
        total_targets = len(quarterly_targets)
        prep_notify_step = tune["prep_notify_step"]
        create_chunk_size = tune["chunk_size"]
        create_notify_every_chunks = tune["create_notify_every_chunks"]

        def _notify_progress(message):
            user = self.env.user
            notify = getattr(user, "notify_info", None)
            if callable(notify):
                try:
                    notify(message=message, title=_("Demo Seed Progress"), sticky=False)
                except Exception:
                    _logger.info("Demo seed progress: %s", message)
            else:
                _logger.info("Demo seed progress: %s", message)

        _notify_progress(
            _("Starting demo seed for %s quarterly target(s) in %s (chunk=%s, prep-step=%s).")
            % (total_targets, fy.display_name, create_chunk_size, prep_notify_step)
        )

        for idx, qt in enumerate(quarterly_targets, start=1):
            # Randomly leave ~28 % of targets unsubmitted so the dashboard shows
            # a realistic mix of Loaded / Not Loaded across indicators and quarters.
            if rng.random() < 0.28:
                skipped += 1
                continue

            indicator = qt.output_indicator_id
            mtype = indicator.measurement_type if indicator else "text"
            workflow_status = rng.choice(_DEMO_WORKFLOW_POOL)
            actual_value = self._generate_demo_actual(
                rng, mtype, qt.planned_target or "10", workflow_status, qt
            )
            comments = rng.choice(_DEMO_COMMENTS)
            deviation = rng.choice(_DEMO_DEVIATIONS)
            remedial = rng.choice(_DEMO_REMEDIALS) if deviation else None

            quarter_label = (qt.quarter_id.code or "QX").upper()
            year_label = fy.name or str(fy.id)
            indicator_name = indicator.name if indicator else "Indicator"

            prepared_rows.append({
                "qt_id": qt.id,
                "quarter_label": quarter_label,
                "year_label": year_label,
                "workflow_status": workflow_status,
                "submission_vals": {
                    "name": f"[DEMO] {indicator_name} \u2014 {quarter_label} {year_label}",
                    "quarterly_target_id": qt.id,
                    "submitted_by": self.env.user.id,
                    "submission_date": fields.Datetime.now(),
                    "workflow_status": workflow_status,
                    "comments": comments,
                    "reason_for_deviation": deviation,
                    "remedial_actions": remedial,
                    "actual_value": actual_value,
                },
            })

            if idx % prep_notify_step == 0:
                _notify_progress(
                    _("Prepared %s/%s targets (%s submissions to create, %s skipped).")
                    % (idx, total_targets, len(prepared_rows), skipped)
                )

        if prepared_rows:
            submission_ctx = dict(
                self.env.context,
                opms_allow_closed_submission_seed=True,
                opms_skip_submission_auto_status_sync=True,
                tracking_disable=True,
                mail_create_nolog=True,
                mail_notrack=True,
                mail_notify_force_send=False,
            )
            evidence_ctx = dict(
                self.env.context,
                opms_skip_submission_auto_status_sync=True,
                tracking_disable=True,
                mail_create_nolog=True,
                mail_notrack=True,
                mail_notify_force_send=False,
            )

            total_to_create = len(prepared_rows)
            evidence_total = 0
            chunk_count = 0
            for start in range(0, total_to_create, create_chunk_size):
                chunk_count += 1
                chunk = prepared_rows[start:start + create_chunk_size]
                submissions = self.env["opms.reporting.submission"].with_context(submission_ctx).create(
                    [row["submission_vals"] for row in chunk]
                )

                evidence_vals = []
                for row, submission in zip(chunk, submissions):
                    if row["workflow_status"] != "draft":
                        evidence_vals.append({
                            "name": f"[DEMO] Evidence \u2014 {row['quarter_label']} {row['year_label']}",
                            "quarterly_target_id": row["qt_id"],
                            "reporting_submission_id": submission.id,
                            "file": dummy_evidence,
                            "file_name": f"demo_evidence_{row['qt_id']}.txt",
                        })

                if evidence_vals:
                    self.env["opms.evidence"].with_context(evidence_ctx).create(evidence_vals)
                    evidence_total += len(evidence_vals)

                created += len(chunk)
                if (chunk_count % create_notify_every_chunks == 0) or (created >= total_to_create):
                    _notify_progress(
                        _("Created %s/%s submissions and %s evidence file(s).")
                        % (created, total_to_create, evidence_total)
                    )

            _notify_progress(
                _("Demo seed completed: %s submissions created, %s skipped.")
                % (created, skipped)
            )

        return {
            "type": "ir.actions.client",
            "tag": "display_notification",
            "params": {
                "title": _("Demo Submissions Loaded"),
                "message": _(
                    "Created: %s demo submission(s).  Left unsubmitted (randomised): %s."
                ) % (created, skipped),
                "type": "success" if created else "warning",
                "sticky": True,
            },
        }

    def _generate_demo_actual(self, rng, measurement_type, planned, workflow_status, qt):
        """Return a plausible demo actual value for the given indicator type."""
        if workflow_status == "draft":
            return None

        if measurement_type == "number":
            try:
                num_str = re.sub(r"[^\d.]", "", str(planned).split()[0].replace(",", "."))
                base = float(num_str) if num_str else 10.0
            except (ValueError, TypeError, IndexError):
                base = 10.0
            actual = round(base * rng.uniform(0.7, 1.4))
            return str(actual)

        if measurement_type == "percentage":
            return str(round(rng.uniform(50.0, 100.0), 1))

        if measurement_type == "date":
            q = qt.quarter_id
            ref = q.end_date if (q and q.end_date) else date.today()
            return (ref + timedelta(days=rng.randint(-20, 10))).strftime("%Y-%m-%d")

        if measurement_type == "boolean":
            return rng.choice(["Yes", "Yes", "Yes", "No"])

        if measurement_type == "milestone":
            return rng.choice([
                "Milestone completed and signed off by the relevant authority.",
                "Milestone achieved within the stipulated timeframe.",
                "Milestone partially achieved; final steps are in progress.",
            ])

        # text / default
        return rng.choice([
            "Activity completed as planned for this quarter.",
            "Deliverable submitted to the relevant authority.",
            "Work is ongoing with no major issues identified.",
        ])
