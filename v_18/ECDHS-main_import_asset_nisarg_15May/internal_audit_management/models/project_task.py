    @api.model_create_multi
    def create(self, vals_list):

        for vals in vals_list:
            if not vals.get('sequence') or vals['sequence'] == _('New'):
                vals['sequence_no'] = self.env['ir.sequence'].next_by_code(
                    'project.task')
            if vals.get('type') and not vals.get('background_body'):
                type_rec = self.env['task.type'].sudo().browse(vals['type'])
                if type_rec.sudo().edms_template and type_rec.sudo().edms_template.background_body:
                    vals[
                        'background_body'] = type_rec.sudo().edms_template.background_body
            # Handle parent task logic
            if vals.get('parent_id'):
                parent_task = self.env['project.task'].browse(int(vals.get('parent_id')))
                vals['stage_id'] = parent_task.stage_id.id
                vals['type'] = parent_task.type.id
                prefix = parent_task.stage_id.prefix or ""
                vals['reference_number'] = f"{prefix}: {parent_task.sub_task_count + 1}"

            # Handle project logic
            if vals.get('project_id'):
                project = self.env['project.project'].browse(int(vals.get('project_id')))
                if project.department_id:
                    vals['hr_team_id'] = project.department_id.id
                    vals['user_ids'] = project.team_member_ids.mapped('user_id')

                    # Optional: reviewer/approver lists
                    user_reviewer_1 = [
                        emp.user_id.id
                        for emp in project.department_id.employee_ids
                        if any(role.type == 'Reviewer_1' for role in emp.role_ids)
                    ]
                    user_reviewer_2 = [
                        emp.user_id.id
                        for emp in project.department_id.employee_ids
                        if any(role.type == 'Reviewer_2' for role in emp.role_ids)
                    ]
                    user_approver = [
                        emp.user_id.id
                        for emp in project.department_id.employee_ids
                        if any(role.type == 'Approver' for role in emp.role_ids)
                    ]
                    # Uncomment if you want to store these IDs in fields
                    # vals['user_reviewer_1_ids'] = user_reviewer_1
                    # vals['user_reviewer_2_ids'] = user_reviewer_2
                    # vals['user_approver_ids'] = user_approver or []
                if not vals.get('user_approver') and project.user_approver:
                    vals['user_approver'] = project.user_approver.id
                if not vals.get('user_preparer_ids') and project.user_preparer_ids:
                    vals['user_preparer_ids'] = project.user_preparer_ids.id
                if not vals.get('user_reviewer_2_ids') and project.user_reviewer_2_ids:
                    vals['user_reviewer_2_ids'] = project.user_reviewer_2_ids.id

        # Create all tasks
        records = super(ProjectTask, self).create(vals_list)
        return records

