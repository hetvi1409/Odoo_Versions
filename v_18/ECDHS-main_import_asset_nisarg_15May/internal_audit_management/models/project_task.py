        def action_import(self):
            """
            Import Audit Program records from an uploaded XLSX file.

            This method validates the uploaded file, reads the XLSX content,
            and creates `audit.pgm` records based on the data in the file.
            Each row in the XLSX file (starting from the second row) is mapped
            to an Audit Program entry and linked to the selected project task.

            Expected XLSX format:
                Column A : (Skipped / Identifier)
                Column B : Process
                Column C : Risk Identified
                Column D : Controls Identified
                Column E : Audit Procedures
                Column F : Timeline
                Column G : Responsibility Assigned To
                Column H : WP Reference

            Raises:
                ValidationError: If no file is uploaded or if the file format is not XLSX.

            Returns:
                dict: Action to close the wizard window after successful import.
            """
            if not self.file:
                raise ValidationError(_("Please upload an XLSX file."))

            if not self.filename or not self.filename.lower().endswith('.xlsx'):
                raise ValidationError(_("Only XLSX files are supported."))

            file_data = base64.b64decode(self.file)
            workbook = load_workbook(
                io.BytesIO(file_data),
                data_only=True,
                read_only=True
            )
            sheet = workbook.active

            AuditPgm = self.env['audit.pgm']
            Risk = self.env['business.risk']
            Category = self.env['risk.category']
            Users = self.env['res.users']
            RiskAnalysis = self.env['risk.analysis']

            for row in sheet.iter_rows(min_row=2, values_only=True):
                if not row or not row[0]:
                    continue
                if self.task_id.task_type == 'exec_1':
                    vals = {
                        'audit_details_id': self.task_id.id,
                        'process': row[1],
                        'risk_identified': row[2],
                        'controls_identified': row[3],
                        'audit_procedures': row[4],
                        'timeline': row[5],
                        'responsibility_assigned_to': row[6],
                        'wp_reference': row[7],
                    }
                    AuditPgm.create(vals)
                elif self.task_id.task_type == 'plan_8':

                    # Many2many: Category
                    category_ids = []
                    if row[2]:
                        category_names = [c.strip() for c in row[2].split(',')]
                        category_ids = Category.search([
                            ('name', 'in', category_names)
                        ]).ids

                    # Many2one: Owner
                    owner_id = False
                    if row[6]:
                        owner = Users.search([('name', '=', row[6])], limit=1)
                        owner_id = owner.id

                    next_date = False
                    cell_value = row[9]

                    if isinstance(cell_value, datetime):
                        next_date = cell_value.date()

                    elif isinstance(cell_value, date):
                        next_date = cell_value

                    elif isinstance(cell_value, time):
                        next_date = False  # ignore pure time values

                    elif isinstance(cell_value, str) and cell_value:
                        try:
                            next_date = datetime.strptime(cell_value,
                                                          '%d-%m-%Y').date()
                        except ValueError:
                            next_date = False
                    vals = {
                        'name': row[1],
                        'category': [(6, 0, category_ids)],
                        'inherent_risk_score': row[3],
                        'control_effectiveness': row[4],
                        'residual_risk_score': row[5],
                        'owner': owner_id,
                        'severity': row[7],
                        'status': row[8],
                        'next_date': next_date,
                    }
                    risk_id =  Risk.create(vals)
                    self.task_id.write({
                        'risk_ids': [(4, risk_id.id)]
                    })
                elif self.task_id.task_type == 'exec_3':
                    vals = {
                        'guidance': row[1],  # Audit Objectives
                        'audit_steps': row[2],  # Audit Procedures
                        'sample_selection': row[3],  # Sample Selection
                        'work_performed': row[4],  # Work Performed
                        'conclusion': row[5],  # Conclusion
                    }

                    # Update task directly
                    self.task_id.write(vals)

                if self.task_id.task_type == 'plan_5':
                    self._import_plan_5(sheet, RiskAnalysis)

                return {'type': 'ir.actions.act_window_close'}

        def _import_plan_5(self, sheet, RiskAnalysis):
                """
                Import risk analysis lines from a plan_5 exported template.

                Template structure:
                    Rows 1-6  : meta header block  (unit, client, project…)
                    Row  7    : blank spacer
                    Row  8    : column headers     ← detected by 'Flow Chart' in col 0
                    Row  9    : sub-headers        (Description / Rating x2)
                    Row  10+  : data rows

                Column mapping (0-based):
                    0  = Flow Chart
                    1  = Activity Description
                    2  = Is Same as Prior Year  ('Yes' / 'No')
                    3  = Risk Description
                    4  = Risk Rating
                    5  = Control Description
                    6  = Control Rating
                    7  = Residual Risk
                    8  = Risk No               ← skipped (informational only)
                    9  = Reporting Point
                    10 = Audit Procedures
                """
                all_rows = list(sheet.iter_rows(values_only=True))

                # Locate the header row by finding 'Flow Chart' in column 0
                data_start = None
                for idx, row in enumerate(all_rows):
                    if row and str(row[0] or '').strip() == 'Flow Chart':
                        data_start = idx + 2  # +1 skips header row, +1 skips sub-header row
                        break

                if data_start is None:
                    raise ValidationError(
                        _("Could not find the 'Flow Chart' header row in the uploaded "
                          "file. Please make sure you are uploading the correct template.")
                    )

                def safe(val):
                    return str(val).strip() if val not in (None, False,
                                                           '') else ''

                for row in all_rows[data_start:]:
                    # Skip blank rows
                    if not row or not any(row):
                        continue

                    # Skip rows where all meaningful columns are empty
                    if not any(row[i] for i in [0, 1, 3, 5, 10] if
                               i < len(row)):
                        continue

                    vals_line = {
                        'task_id': self.task_id.id,
                        'flow_chart': safe(row[0]),
                        'activity_description': safe(row[1]),
                        'is_same_prior_year': str(
                            row[2] or '').strip().lower() == 'yes',
                        'risk_description': safe(row[3]),
                        'rating': safe(row[4]),
                        'control_description': safe(row[5]),
                        'control_rating': safe(row[6]),
                        'residual_risk': safe(row[7]),
                        # col 8 (Risk No) intentionally skipped
                        'reporting_point': safe(row[9]) if len(
                            row) > 9 else '',
                        'audit_procedures': safe(row[10]) if len(
                            row) > 10 else '',
                    }

                    RiskAnalysis.create(vals_line)
